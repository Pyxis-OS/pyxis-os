#define RTL_MAC_TUNE_E052_SET 0x8008u
#define RTL_MAC_TUNE_E0D6 0xe0d6
#define RTL_MAC_TUNE_E0D6_CLEAR 0x01ffu
#define RTL_MAC_TUNE_E0D6_SET 0x017fu
#define RTL_MAC_TUNE_D420 0xd420
#define RTL_MAC_TUNE_D420_SET 0x047fu
#define RTL_MAC_TUNE_E63E 0xe63e
#define RTL_MAC_TUNE_E63E_START 0x0001u
#define RTL_MAC_TUNE_C094 0xc094
#define RTL_MAC_TUNE_C09E 0xc09e

#define RTL_EPHY_TIMEOUT_NS UINT64_C(1000000)
