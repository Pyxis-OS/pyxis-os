#define RTL_INTERRUPT_MITIGATION 0xe2
#define RTL_RX_RING_LOW 0xe4
#define RTL_RX_RING_HIGH 0xe8
#define RTL_TX_MAXIMUM 0xec
#define RTL_TX_EARLY_SIZE 0x27u

#define RTL_INTERRUPT_RX_OK (1u << 0)
#define RTL_INTERRUPT_RX_ERROR (1u << 1)
#define RTL_INTERRUPT_TX_OK (1u << 2)
#define RTL_INTERRUPT_TX_ERROR (1u << 3)
#define RTL_INTERRUPT_LINK (1u << 5)
#define RTL_INTERRUPT_IO (RTL_INTERRUPT_RX_OK | RTL_INTERRUPT_RX_ERROR | \
                          RTL_INTERRUPT_TX_OK | RTL_INTERRUPT_TX_ERROR | RTL_INTERRUPT_LINK)

#define RTL_RX_STATUS_CRC (1u << 19)
#define RTL_RX_STATUS_RUNT (1u << 20)
#define RTL_RX_STATUS_ERROR (1u << 21)
#define RTL_RX_STATUS_WATCHDOG (1u << 22)
#define RTL_RX_STATUS_ERRORS (RTL_RX_STATUS_CRC | RTL_RX_STATUS_RUNT | \
                              RTL_RX_STATUS_ERROR | RTL_RX_STATUS_WATCHDOG)

#define RTL_ERI_LOW_BYTE (1u << 12)
#define RTL_ERI_LOW_HALF (3u << 12)
#define RTL_ERI_RX_FIFO 0xc8
#define RTL_ERI_TX_FIFO 0xe8
#define RTL_ERI_RX_FIFO_8168H 0x00080002u
#define RTL_ERI_TX_FIFO_8168H 0x00100006u
#define RTL_ERI_PAUSE_LOW 0xcc
#define RTL_ERI_PAUSE_HIGH 0xd0
#define RTL_ERI_PAUSE_LOW_8168H 0x38u
#define RTL_ERI_PAUSE_HIGH_8168H 0x48u
