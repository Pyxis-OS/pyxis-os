#define RTL_EPHY_TUNE_1D 0x1d
#define RTL_EPHY_TUNE_1D_SET 0x0800u
#define RTL_EPHY_TUNE_05 0x05
#define RTL_EPHY_TUNE_05_VALUE 0x2089u
#define RTL_EPHY_TUNE_06 0x06
#define RTL_EPHY_TUNE_06_VALUE 0x5881u
#define RTL_EPHY_TUNE_04 0x04
#define RTL_EPHY_TUNE_04_VALUE 0x854au
#define RTL_EPHY_TUNE_01 0x01
#define RTL_EPHY_TUNE_01_VALUE 0x068bu

#define RTL_PHY_SAW_COUNT 0xc426
#define RTL_PHY_SAW_COUNT_MASK 0x3fffu
#define RTL_MAC_SAW_TIMER 0xd412
#define RTL_MAC_SAW_CLOCK_HZ 16000000u
#define RTL_MAC_TIMER_MASK 0x0fffu
#define RTL_MAC_TUNE_E056 0xe056
