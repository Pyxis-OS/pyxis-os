#ifndef USB_SETTINGS_H
#define USB_SETTINGS_H

/* Initial resource/deadline choices, independent of image and machine sizes. */
#define USB_STATE_TIMEOUT_MS 1000
#define USB_COMMAND_TIMEOUT_MS 5000
#define USB_CONTROL_TIMEOUT_MS 5000
/* USB 2.0 sections 9.2.6.2 and 9.2.6.3: protocol recovery minima. */
#define USB_RESET_RECOVERY_MS 10
#define USB_ADDRESS_RECOVERY_MS 2
#define USB_ENUMERATION_TIMEOUT_MS 30000
#define USB_PORT_POWER_DELAY_MS 20
#define USB_ROOT_SETTLE_MIN_MS 100
/* Boot-latency policy near the nominal 360 ms Polling.LFPS timeout, not a
 * worst-case completion guarantee across timer tolerances and retries. */
#define USB_ROOT_SETTLE_MAX_MS 400
#define USB_WORKER_POLL_MS 10
#define USB_CONTROL_BYTES 4096
#define USB_BULK_BYTES 65536
#define USB_STORAGE_DEVICE_BUDGET 4
#define USB_ASYNC_BULK_DEVICE_BUDGET 1
#define USB_ASYNC_BULK_BYTES 4096
#define USB_ASYNC_BULK_RECEIVES 2
#define USB_ASYNC_BULK_COMPLETIONS 8
#define USB_NETWORK_CANDIDATES 2
#define USB_NETWORK_REPLACEMENTS 4
#define USB_NETWORK_INITIAL_RETRIES 2
#define USB_NETWORK_PATH_COMPONENTS 6
#define USB_NETWORK_RECOVERY_POLL_MS 100
#define USB_NETWORK_BULK_BYTES 16384
#define USB_NETWORK_INTERRUPT_BYTES 1024
#define USB_NETWORK_TX_DELAY_MS 1
/* Longest receive pause for a full network provider before frames are dropped. */
#define USB_NETWORK_RX_STALL_MS 50
#define USB_NETWORK_STREAMS \
  (USB_NETWORK_CANDIDATES * (1 + USB_NETWORK_INITIAL_RETRIES + USB_NETWORK_REPLACEMENTS))
/* Maximum HCI event: two header bytes plus 255 parameter bytes. */
#define USB_INTERRUPT_BYTES 257
/* USB 2 high-speed interrupt endpoints permit 1024-byte packets. */
#define USB_HID_INTERRUPT_BYTES 1024
/* Additional fresh contexts beyond the prepared network retry/path budget. */
#define USB_TOPOLOGY_DEVICE_BUDGET 32
#define USB_TOPOLOGY_NCM_RESERVE (USB_NETWORK_CANDIDATES * USB_NETWORK_PATH_COMPONENTS)
#define USB_TOPOLOGY_RECORDS (USB_TOPOLOGY_DEVICE_BUDGET + USB_TOPOLOGY_NCM_RESERVE)
#define USB_TOPOLOGY_CONNECTION_ATTEMPTS 8
#define USB_TOPOLOGY_RETRIES 3
#define USB_TOPOLOGY_RETRY_MS 1000
#define USB_HID_DEVICE_BUDGET 32
#define USB_HID_ENDPOINTS_PER_DEVICE 2
#define USB_HUB_INTERRUPT_DEVICE_BUDGET 32
#define USB_INTERRUPT_RECEIVES 2
#define USB_INTERRUPT_COMPLETIONS 8
#define USB_BOT_TIMEOUT_MS 5000
#define USB_BOT_RECOVERY_TIMEOUT_MS 5000
#define USB_INTERFACE_BUDGET 512
#define USB_DESCENDANT_BUDGET 32
#define USB_HUB_POLL_MS 10
#define USB_HUB_DEBOUNCE_MS 100
#define USB_HUB_RESET_TIMEOUT_MS 1000

#endif
